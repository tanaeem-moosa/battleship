//! Battleship Simulator Engine CLI & Server.
//!
//! Subcommands:
//! - `simulate [--games N] [--seed S]` (default: 1000 games benchmark + writes viewer/sample_data.js)
//! - `match [--p1 P1] [--p2 P2] [--seed S]` (single match JSON to stdout)
//! - `serve [--port PORT]` (HTTP static file and API server on 127.0.0.1:PORT)

use std::fs;
use std::path::Path;

use battleship::server::{create_strategy, run_server};
use battleship::sim::{
    print_benchmark_summary, run_benchmark, simulate_match, BenchmarkReport, MatchReplay,
};
use battleship::strategy::RandomDefense;

fn print_help() {
    println!(
        r#"Battleship Simulator Engine (Standard Hasbro Rules)

USAGE:
    cargo run -- [SUBCOMMAND] [OPTIONS]

SUBCOMMANDS:
    simulate (default)  Run multi-game statistical benchmark of all 6 attack strategies
                        and complete 6x6 round-robin head-to-head tournament.
                        Prints summary table, tournament standings, 6x6 matrix &
                        ASCII histogram to stdout, and writes `viewer/sample_data.js`.
                        Options:
                          --games <N>    Number of games per strategy (default: 1000)
                          --seed <S>     PRNG seed for reproducible results (default: 42)

    match               Simulate a single head-to-head match and print JSON to stdout.
                        Options:
                          --p1 <STRAT>   Player 1 strategy (default: random_hunt)
                          --p2 <STRAT>   Player 2 strategy (default: checkerboard)
                                         Available:
                                           - random_hunt     ("Random + Hunt/Target")
                                           - checkerboard    ("Checkerboard + Hunt/Target")
                                           - largest_rect    ("Largest Empty Rect Midpoint")
                                           - adaptive_stride ("Adaptive Stride (2->3->4->5)")
                                           - stride4_to_2    ("Staggered Stride (4->2)")
                                           - rect_stride4    ("Largest Rect + Stride (4->2)")
                          --seed <S>     PRNG seed (default: 42)

    serve               Start local HTTP server serving web viewer and REST APIs.
                        Options:
                          --port <PORT>  HTTP port (default: 8080)

    help, -h, --help    Print this help menu.

EXAMPLES:
    cargo run -- simulate --games 1000 --seed 42
    cargo run -- match --p1 rect_stride4 --p2 checkerboard --seed 123
    cargo run -- serve --port 8080
"#
    );
}

fn write_sample_data_file(
    report: &BenchmarkReport,
    matches: &[MatchReplay],
) -> std::io::Result<()> {
    let viewer_dir = Path::new("viewer");
    if !viewer_dir.exists() {
        fs::create_dir_all(viewer_dir)?;
    }

    let matches_json: Vec<String> = matches.iter().map(|m| m.to_json()).collect();
    let content = format!(
        "// Auto-generated by Battleship Simulator Engine (Rust std)\n\
         window.BATTLESHIP_SAMPLE_DATA = {{\n  \
             \"benchmark\": {},\n  \
             \"sample_matches\": [\n    {}\n  ]\n\
         }};\n",
        report.to_json(),
        matches_json.join(",\n    ")
    );

    let path = viewer_dir.join("sample_data.js");
    fs::write(&path, content)?;
    println!("\nWrote sample simulation data to {}", path.display());
    Ok(())
}

fn run_simulate_cmd(args: &[String]) -> Result<(), Box<dyn std::error::Error>> {
    let mut games: usize = 1000;
    let mut seed: u64 = 42;

    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--games" | "-g" => {
                if i + 1 < args.len() {
                    games = args[i + 1].parse().unwrap_or(1000);
                    i += 1;
                }
            }
            "--seed" | "-s" => {
                if i + 1 < args.len() {
                    seed = args[i + 1].parse().unwrap_or(42);
                    i += 1;
                }
            }
            _ => {}
        }
        i += 1;
    }

    println!("Running Battleship benchmark ({} games per strategy, seed {})...", games, seed);
    let report = run_benchmark(games, seed);
    print_benchmark_summary(&report);

    // Pre-generate 6 diverse sample matches showcasing all strategies for the browser viewer:
    let sample_configs = [
        ("Random + Hunt/Target", "random_hunt", "Checkerboard + Hunt/Target", "checkerboard", seed),
        ("Checkerboard + Hunt/Target", "checkerboard", "Largest Rect + Stride (4->2)", "rect_stride4", seed + 101),
        ("Staggered Stride (4->2)", "stride4_to_2", "Adaptive Stride (2->3->4->5)", "adaptive_stride", seed + 202),
        ("Largest Empty Rect Midpoint", "largest_rect", "Random + Hunt/Target", "random_hunt", seed + 303),
        ("Largest Rect + Stride (4->2)", "rect_stride4", "Staggered Stride (4->2)", "stride4_to_2", seed + 777),
        ("Adaptive Stride (2->3->4->5)", "adaptive_stride", "Checkerboard + Hunt/Target", "checkerboard", seed + 999),
    ];

    let mut sample_matches = Vec::new();
    for (name1, id1, name2, id2, s) in sample_configs {
        let (mut p1_att, _) = create_strategy(id1);
        let (mut p2_att, _) = create_strategy(id2);
        let mut def1 = RandomDefense::new();
        let mut def2 = RandomDefense::new();
        let replay = simulate_match(
            name1,
            p1_att.as_mut(),
            &mut def1,
            name2,
            p2_att.as_mut(),
            &mut def2,
            s,
        );
        sample_matches.push(replay);
    }

    if let Err(e) = write_sample_data_file(&report, &sample_matches) {
        eprintln!("Warning: could not write viewer/sample_data.js: {}", e);
    }

    Ok(())
}

fn run_match_cmd(args: &[String]) -> Result<(), Box<dyn std::error::Error>> {
    let mut p1_id = "random_hunt".to_string();
    let mut p2_id = "checkerboard".to_string();
    let mut seed: u64 = 42;

    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--p1" => {
                if i + 1 < args.len() {
                    p1_id = args[i + 1].clone();
                    i += 1;
                }
            }
            "--p2" => {
                if i + 1 < args.len() {
                    p2_id = args[i + 1].clone();
                    i += 1;
                }
            }
            "--seed" | "-s" => {
                if i + 1 < args.len() {
                    seed = args[i + 1].parse().unwrap_or(42);
                    i += 1;
                }
            }
            _ => {}
        }
        i += 1;
    }

    let (mut p1_att, p1_name) = create_strategy(&p1_id);
    let (mut p2_att, p2_name) = create_strategy(&p2_id);
    let mut def1 = RandomDefense::new();
    let mut def2 = RandomDefense::new();

    let replay = simulate_match(
        p1_name,
        p1_att.as_mut(),
        &mut def1,
        p2_name,
        p2_att.as_mut(),
        &mut def2,
        seed,
    );

    println!("{}", replay.to_json());
    Ok(())
}

fn run_serve_cmd(args: &[String]) -> Result<(), Box<dyn std::error::Error>> {
    let mut port: u16 = 8080;

    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--port" | "-p" => {
                if i + 1 < args.len() {
                    port = args[i + 1].parse().unwrap_or(8080);
                    i += 1;
                }
            }
            _ => {}
        }
        i += 1;
    }

    run_server(port)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let raw_args: Vec<String> = std::env::args().skip(1).collect();

    if raw_args.is_empty() {
        // Default behavior: run simulation
        return run_simulate_cmd(&[]);
    }

    let subcommand = raw_args[0].to_ascii_lowercase();
    let sub_args = &raw_args[1..];

    match subcommand.as_str() {
        "simulate" | "sim" | "benchmark" => run_simulate_cmd(sub_args),
        "match" | "play" => run_match_cmd(sub_args),
        "serve" | "server" => run_serve_cmd(sub_args),
        "help" | "--help" | "-h" => {
            print_help();
            Ok(())
        }
        _ => {
            // Check if user passed flags directly without subcommand (e.g. `--games 500`)
            if subcommand.starts_with('-') {
                run_simulate_cmd(&raw_args)
            } else {
                eprintln!("Unknown subcommand: '{}'", subcommand);
                print_help();
                std::process::exit(1);
            }
        }
    }
}
